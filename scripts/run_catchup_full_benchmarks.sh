#!/usr/bin/env bash
# CatchUp final LIVE-reference benchmark run
#
# Runs:
#   Grounding: RefCOCO / RefCOCO+ / RefCOCOg (8 splits total)
#   MLLM:      MM-Vet / MMBench / POPE / GQA / VizWiz / VQAv2
#   Budgets:   avg64 / avg128 / avg192
#   GPUs:      0,1 / 2,3 / 4,5 (two queues per budget)
#
# Queue layout:
#   GPU 0: avg64  -> mmvet, pope, vizwiz_vqa_val, cat_grounding
#   GPU 1: avg64  -> mmbench, gqa, vqav2_val
#   GPU 2: avg128 -> mmvet, pope, vizwiz_vqa_val, cat_grounding
#   GPU 3: avg128 -> mmbench, gqa, vqav2_val
#   GPU 4: avg192 -> mmvet, pope, vizwiz_vqa_val, cat_grounding
#   GPU 5: avg192 -> mmbench, gqa, vqav2_val
#
# NOTE:
# Create a temporary all-eight-split grounding evaluation config.
# To guarantee all 8 grounding splits without modifying the repository file,
# this script creates a temporary aggregate eval config and maps the logical
# task "cat_grounding" to that config. The temporary file is removed on exit.

set -euo pipefail

# ============================================================
# Project / environment
# ============================================================

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${PROJECT_ROOT}"

export API_TYPE="openai"
export OPENAI_API_URL="${OPENAI_API_URL:-https://api.openai.com/v1}"
export MODEL_VERSION="${MODEL_VERSION:-gpt-4o-2024-11-20}"

export HF_HOME="${HF_HOME:-${HOME}/.cache/huggingface}"
export HF_DATASETS_CACHE="${HF_DATASETS_CACHE:-${HF_HOME}/datasets}"
export HUGGINGFACE_HUB_CACHE="${HUGGINGFACE_HUB_CACHE:-${HF_HOME}/hub}"
export HF_ENDPOINT="${HF_ENDPOINT:-https://huggingface.co}"

export PYTHONUNBUFFERED=1
export CONDA_ENV="${CONDA_ENV:-reroute}"

mkdir -p \
  "${HF_HOME}" \
  "${HF_DATASETS_CACHE}" \
  "${HUGGINGFACE_HUB_CACHE}"

if [[ -f "${HF_HOME}/token" ]]; then
  export HF_TOKEN="$(cat "${HF_HOME}/token")"
  export HUGGING_FACE_HUB_TOKEN="${HF_TOKEN}"
elif [[ -f "${HOME}/.cache/huggingface/token" ]]; then
  export HF_TOKEN="$(cat "${HOME}/.cache/huggingface/token")"
  export HUGGING_FACE_HUB_TOKEN="${HF_TOKEN}"
fi

# MM-Vet is included in the final benchmark set.
: "${OPENAI_API_KEY:?OPENAI_API_KEY is required because this run includes mmvet.}"

# ============================================================
# Final CatchUp setting: Q-VER routing + LTC + LIVE reference
# ============================================================

# Shared inference settings; avoids diverging benchmark/profiler parameters.
source "${PROJECT_ROOT}/scripts/catchup_env.sh"

# ============================================================
# Full grounding aggregate config
# ============================================================
# Logical task shown in logs: cat_grounding
# Actual temporary Hydra eval config: all 8 grounding splits in one model run.

GROUNDING_EVAL_TASK="cat_grounding_live_all_${$}"
GROUNDING_EVAL_FILE="${PROJECT_ROOT}/configs/eval/${GROUNDING_EVAL_TASK}.yaml"

cat > "${GROUNDING_EVAL_FILE}" <<'YAML'
# Auto-generated by run_catchup_full_benchmarks.sh
# Full referring-expression grounding evaluation.
benchmarks:
  - refcoco_bbox_rec_val
  - refcoco_bbox_rec_testA
  - refcoco_bbox_rec_testB
  - refcoco+_bbox_rec_val
  - refcoco+_bbox_rec_testA
  - refcoco+_bbox_rec_testB
  - refcocog_bbox_rec_val
  - refcocog_bbox_rec_test
batch_size: 1
log_samples: true
YAML

cleanup() {
  rm -f "${GROUNDING_EVAL_FILE}"
}
trap cleanup EXIT INT TERM

echo "================================================================"
echo "[GROUNDING CONFIG]"
echo "Logical task : cat_grounding"
echo "Eval config  : ${GROUNDING_EVAL_TASK}"
echo "Splits       : RefCOCO 3 + RefCOCO+ 3 + RefCOCOg 2 = 8"
echo "================================================================"

# ============================================================
# Budget configs
# ============================================================

CFG_64="llava15/avg64/llava15_qver_avg64"
CFG_128="llava15/avg128/llava15_qver_avg128"
CFG_192="llava15/avg192/llava15_qver_avg192"

# ============================================================
# GPU assignment
# ============================================================

GPU_64_A="${GPU_64_A:-0}"
GPU_64_B="${GPU_64_B:-1}"

GPU_128_A="${GPU_128_A:-2}"
GPU_128_B="${GPU_128_B:-3}"

GPU_192_A="${GPU_192_A:-4}"
GPU_192_B="${GPU_192_B:-5}"

# Two queues per budget.
TASKS_A=(
  mmvet
  pope
  vizwiz_vqa_val
  cat_grounding
)

TASKS_B=(
  mmbench
  gqa
  vqav2_val
)

# ============================================================
# Logs
# ============================================================

LOG_ROOT="${LOG_ROOT:-experiments/catchup_live_full_avg64_128_192}"
LAUNCH_LOG_DIR="${LOG_ROOT}/launcher_logs"
FAILED_RUNS_FILE="${LOG_ROOT}/failed_runs.txt"

mkdir -p "${LAUNCH_LOG_DIR}"
: > "${FAILED_RUNS_FILE}"

# ============================================================
# Run one budget x task
# ============================================================

run_one() {
  local gpu="$1"
  local budget="$2"
  local cfg="$3"
  local logical_task="$4"

  local eval_task="${logical_task}"
  if [[ "${logical_task}" == "cat_grounding" ]]; then
    eval_task="${GROUNDING_EVAL_TASK}"
  fi

  local safe_cfg
  local log_file
  local exit_code
  local log_has_failure=0

  safe_cfg="$(echo "${cfg}" | tr '/' '_')"
  log_file="${LAUNCH_LOG_DIR}/live_avg${budget}__${safe_cfg}__${logical_task}__gpu${gpu}.log"

  echo "================================================================"
  echo "[START]   CatchUp LIVE"
  echo "[GPU]     ${gpu}"
  echo "[BUDGET]  avg${budget}"
  echo "[CONFIG]  ${cfg}"
  echo "[TASK]    ${logical_task}"
  if [[ "${logical_task}" == "cat_grounding" ]]; then
    echo "[EVAL]    ${eval_task} (8 grounding splits)"
  else
    echo "[EVAL]    ${eval_task}"
  fi
  echo "[TIME]    $(date '+%F %T')"
  echo "[LOG]     ${log_file}"
  echo "================================================================"

  set +e

  CUDA_VISIBLE_DEVICES="${gpu}" \
  HYDRA_FULL_ERROR=1 \
  PYTHONUNBUFFERED=1 \
  bash scripts/run_setting.sh \
    "${cfg}" \
    --tasks "${eval_task}" \
    --gpu "${gpu}" \
    --log-dir "${LOG_ROOT}" \
    2>&1 | tee "${log_file}"

  exit_code=${PIPESTATUS[0]}

  set -e

  if grep -qE '^===== .*: FAIL .*=====$' "${log_file}"; then
    log_has_failure=1
  fi

  if [[ "${exit_code}" -ne 0 || "${log_has_failure}" -eq 1 ]]; then
    echo "================================================================"
    echo "[FAIL]    CatchUp LIVE"
    echo "[GPU]     ${gpu}"
    echo "[BUDGET]  avg${budget}"
    echo "[TASK]    ${logical_task}"
    echo "[EXIT]    ${exit_code}"
    echo "[LOGFAIL] ${log_has_failure}"
    echo "[LOG]     ${log_file}"
    echo "[INFO]    Continuing with the next task in this GPU queue."
    echo "================================================================"

    printf '%s\tGPU=%s\tBUDGET=avg%s\tCONFIG=%s\tTASK=%s\tEVAL=%s\tEXIT=%s\tLOG_FAIL=%s\tLOG=%s\n' \
      "$(date '+%F %T')" \
      "${gpu}" \
      "${budget}" \
      "${cfg}" \
      "${logical_task}" \
      "${eval_task}" \
      "${exit_code}" \
      "${log_has_failure}" \
      "${log_file}" \
      >> "${FAILED_RUNS_FILE}"

    return 0
  fi

  echo "================================================================"
  echo "[DONE]    CatchUp LIVE"
  echo "[GPU]     ${gpu}"
  echo "[BUDGET]  avg${budget}"
  echo "[TASK]    ${logical_task}"
  echo "[TIME]    $(date '+%F %T')"
  echo "================================================================"
}

# ============================================================
# Run one sequential GPU queue
# ============================================================

run_queue() {
  local gpu="$1"
  local budget="$2"
  local cfg="$3"
  shift 3
  local tasks=("$@")

  echo "################################################################"
  echo "[QUEUE START]"
  echo "[GPU]     ${gpu}"
  echo "[BUDGET]  avg${budget}"
  echo "[CONFIG]  ${cfg}"
  echo "[TASKS]   ${tasks[*]}"
  echo "[POLICY]  LIVE reference"
  echo "[TIME]    $(date '+%F %T')"
  echo "################################################################"

  local task
  for task in "${tasks[@]}"; do
    run_one "${gpu}" "${budget}" "${cfg}" "${task}"
  done

  echo "################################################################"
  echo "[QUEUE DONE]"
  echo "[GPU]     ${gpu}"
  echo "[BUDGET]  avg${budget}"
  echo "[TIME]    $(date '+%F %T')"
  echo "################################################################"
}

# ============================================================
# Launch six queues in parallel
# ============================================================

PIDS=()
QUEUE_NAMES=()

run_queue "${GPU_64_A}" 64 "${CFG_64}" "${TASKS_A[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg64-A/GPU${GPU_64_A}")

run_queue "${GPU_64_B}" 64 "${CFG_64}" "${TASKS_B[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg64-B/GPU${GPU_64_B}")

run_queue "${GPU_128_A}" 128 "${CFG_128}" "${TASKS_A[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg128-A/GPU${GPU_128_A}")

run_queue "${GPU_128_B}" 128 "${CFG_128}" "${TASKS_B[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg128-B/GPU${GPU_128_B}")

run_queue "${GPU_192_A}" 192 "${CFG_192}" "${TASKS_A[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg192-A/GPU${GPU_192_A}")

run_queue "${GPU_192_B}" 192 "${CFG_192}" "${TASKS_B[@]}" &
PIDS+=("$!")
QUEUE_NAMES+=("avg192-B/GPU${GPU_192_B}")

echo
echo "================================================================"
echo "All 6 CatchUp LIVE queues launched."
for i in "${!PIDS[@]}"; do
  echo "  ${QUEUE_NAMES[$i]} : PID ${PIDS[$i]}"
done
echo "================================================================"

# ============================================================
# Wait
# ============================================================

STATUSES=()

set +e
for i in "${!PIDS[@]}"; do
  wait "${PIDS[$i]}"
  STATUSES[$i]=$?
done
set -e

# ============================================================
# Final summary
# ============================================================

echo
echo "================================================================"
echo "CatchUp LIVE full benchmark finished."
echo "TIME: $(date '+%F %T')"
echo "ROOT: ${LOG_ROOT}"
echo
echo "Queue exit statuses:"
for i in "${!PIDS[@]}"; do
  echo "  ${QUEUE_NAMES[$i]} : ${STATUSES[$i]}"
done
echo "================================================================"

if [[ -s "${FAILED_RUNS_FILE}" ]]; then
  echo
  echo "================================================================"
  echo "Some individual runs failed."
  echo "Failed run list: ${FAILED_RUNS_FILE}"
  echo "================================================================"
  cat "${FAILED_RUNS_FILE}"
else
  echo
  echo "================================================================"
  echo "All 21 logical runs completed without recorded failures."
  echo "  6 MLLM tasks x 3 budgets = 18"
  echo "  cat_grounding x 3 budgets = 3"
  echo "  grounding aggregate = 8 splits per budget"
  echo "================================================================"
  rm -f "${FAILED_RUNS_FILE}"
fi
